"""Generate static demo text tables from SQLite's unicode61 tokenizer and Python casefold."""

from __future__ import annotations

import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build_tables():
    connection = sqlite3.connect(":memory:")
    connection.execute("CREATE VIRTUAL TABLE words USING fts5(text)")
    connection.execute("CREATE VIRTUAL TABLE tokens USING fts5vocab(words, instance)")
    separators, ignored, folds, casefolds = [], [], {}, {}
    for start in range(0, 0x110000, 4096):
        points = [
            point
            for point in range(start, min(start + 4096, 0x110000))
            if not 0xD800 <= point <= 0xDFFF
        ]
        connection.execute("DELETE FROM words")
        connection.executemany(
            "INSERT INTO words(rowid, text) VALUES (?, ?)",
            ((point + 1, "0" + chr(point) + "0") for point in points),
        )
        tokens = {}
        for doc, term in connection.execute("SELECT doc, term FROM tokens ORDER BY doc, offset"):
            tokens.setdefault(doc - 1, []).append(term)
        for point in points:
            char = chr(point)
            result = tokens.get(point, [])
            if len(result) != 1 or not result[0].startswith("0") or not result[0].endswith("0"):
                separators.append(point)
            else:
                folded = result[0][1:-1]
                if not folded:
                    ignored.append(point)
                elif folded != char:
                    folds[char] = folded
            if char.casefold() != char:
                casefolds[char] = char.casefold()
    connection.close()

    def ranges(points):
        result = []
        for point in points:
            if result and result[-1][1] + 1 == point:
                result[-1][1] = point
            else:
                result.append([point, point])
        return result

    return {
        "separators": ranges(separators),
        "ignored": ranges(ignored),
        "folds": folds,
        "casefolds": casefolds,
    }


def render_tables(tables):
    # Generated tables are data; wrapping each section keeps the asset inspectable.
    sections = []
    for name, value in tables.items():
        items = list(value.items()) if isinstance(value, dict) else value
        lines = []
        for start in range(0, len(items), 8):
            chunk = items[start : start + 8]
            if isinstance(value, dict):
                lines.append(json.dumps(dict(chunk), ensure_ascii=True)[1:-1])
            else:
                lines.append(json.dumps(chunk)[1:-1])
        opening, closing = ("{", "}") if isinstance(value, dict) else ("[", "]")
        sections.append(
            f"    {name}: {opening}\n        " + ",\n        ".join(lines) + f"\n    {closing}"
        )
    return (
        "/* Generated by scripts/build_demo_search_unicode.py; do not edit by hand. */\n"
        "window.TweetNookDemoUnicode = {\n" + ",\n".join(sections) + "\n};\n"
    )


if __name__ == "__main__":
    (ROOT / "demo/search-unicode.js").write_text(render_tables(build_tables()))
